"""Ultralytics YOLO backend implementing the vision detector protocol.

The heavy ``ultralytics`` dependency is imported lazily inside method bodies so
that lightweight modules (data contracts, evidence, config) can import this
module without pulling in the training stack.

Dataset descriptors (``data.yaml``) are generated exclusively from immutable
split manifests; raw dataset paths are never hard-coded here.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any

from railway_detection.config.exceptions import ConfigError
from railway_detection.data.split import SplitSummary
from railway_detection.fusion.evidence import Detection
from railway_detection.utils.logging import get_logger

logger = get_logger("vision.yolo")


class UltralyticsYOLOAdapter:
    """YOLOv8/v11-compatible backend for the Ultralytics framework."""

    backend_name = "ultralytics_yolo"

    def __init__(self) -> None:
        self._model: Any = None

    def prepare_dataset(
        self,
        split_summary: SplitSummary,
        output_dir: Path,
        dataset_root: Path | None = None,
        class_mapping: dict[str, int] | None = None,
    ) -> Path:
        """Write a backend ``data.yaml`` descriptor from split manifests."""
        output_dir.mkdir(parents=True, exist_ok=True)
        descriptor = output_dir / "data.yaml"

        root = dataset_root or Path("data/raw/vision/v1/baler.v1i.yolov8")
        if not root.is_absolute():
            root = root.resolve()

        txt_files: dict[str, Path] = {}
        for partition_name in ("train", "val", "test"):
            sample_ids = split_summary.partitions.get(partition_name, [])
            txt_path = output_dir / f"{partition_name}.txt"
            lines = []
            for sample_id in sample_ids:
                img_path = root / f"{sample_id}.jpg"
                if not img_path.exists():
                    img_path = root / f"{sample_id}.png"
                if not img_path.exists():
                    img_path = root / sample_id
                lines.append(str(img_path.resolve()))
            txt_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
            txt_files[partition_name] = txt_path

        if class_mapping:
            id_to_name = {cid: name for name, cid in class_mapping.items()}
            class_names = [id_to_name[i] for i in range(len(class_mapping))]
        else:
            class_names = ["front", "rear", "side"]

        lines = [
            "# Generated by railway_detection from frozen split manifests.",
            f"split_id: {split_summary.split_id}",
            f"path: {str(output_dir.resolve())}",
            "train: train.txt",
            "val: val.txt",
            "test: test.txt",
            f"nc: {len(class_names)}",
            f"names: {class_names!r}",
        ]
        descriptor.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return descriptor.resolve()

    def train(self, config: object, data_descriptor: Path, output_dir: Path) -> Path:
        """Execute Ultralytics training and return the best checkpoint path."""
        try:
            from ultralytics import YOLO  # type: ignore[import-not-found]
        except ImportError as exc:
            raise ConfigError(
                "ultralytics is not installed; add it to the environment to "
                "run real YOLO training (mock training runs do not need it)"
            ) from exc

        training_cfg = getattr(config, "training", {})
        if not isinstance(training_cfg, dict):
            training_cfg = {}

        model_name = training_cfg.get("model_name") or getattr(config, "model_name", "yolov8n.pt")
        epochs = training_cfg.get("epochs") or getattr(config, "epochs", 100)
        batch_size = training_cfg.get("batch_size") or getattr(config, "batch_size", 16)
        device = getattr(config, "device", "cpu")
        seed = getattr(config, "seed", 42)
        image_size = getattr(config, "image_size", 640)
        if isinstance(image_size, (list, tuple)):
            image_size = image_size[0]
        workers = training_cfg.get("workers", 4)
        lr0 = training_cfg.get("lr0", 0.01)
        optimizer = training_cfg.get("optimizer", "auto")

        model = YOLO(str(model_name or "yolov8n.pt"))
        results = model.train(
            data=str(Path(data_descriptor).resolve()),
            imgsz=image_size,
            epochs=epochs,
            batch=batch_size,
            device=device,
            seed=seed,
            workers=workers,
            lr0=lr0,
            optimizer=optimizer,
            project=str(output_dir.parent.resolve()),
            name=output_dir.name,
            verbose=True,
        )
        best_path = Path(results.save_dir) / "weights" / "best.pt"
        if not best_path.exists():
            raise ConfigError(
                f"training completed but checkpoint not found at {best_path}"
            )
        return best_path

    def evaluate(self, checkpoint_path: Path, split_manifest: Path) -> dict[str, float]:
        """Evaluate a checkpoint against a held-out split manifest."""
        try:
            from ultralytics import YOLO  # type: ignore[import-not-found]
        except ImportError as exc:
            raise ConfigError("ultralytics is not installed") from exc

        model = YOLO(str(checkpoint_path))
        metrics = model.val(split=str(split_manifest))
        return {
            "mAP50": float(metrics.box.map50),
            "mAP50_95": float(metrics.box.map),
        }

    def load(self, checkpoint_path: Path) -> None:
        try:
            from ultralytics import YOLO  # type: ignore[import-not-found]
        except ImportError as exc:
            raise ConfigError("ultralytics is not installed") from exc
        self._model = YOLO(str(checkpoint_path))

    def predict(self, image: object, conf: float, iou: float) -> list[Detection]:
        results = self._predict_raw([image], conf=conf, iou=iou)
        return results[0] if results else []

    def predict_batch(
        self, images: list[object], conf: float, iou: float
    ) -> list[list[Detection]]:
        return self._predict_raw(images, conf=conf, iou=iou)

    def _predict_raw(
        self, images: list[object], conf: float, iou: float
    ) -> list[list[Detection]]:
        if self._model is None:
            raise ConfigError("model is not loaded; call load(checkpoint) first")
        outputs: list[list[Detection]] = []
        for result in self._model.predict(
            source=images, conf=conf, iou=iou, verbose=False
        ):
            detections: list[Detection] = []
            for box in result.boxes:
                label_index = int(box.cls[0])
                name = result.names.get(label_index, str(label_index))
                xyxy_raw = box.xyxy[0]
                xyxy_float = tuple(float(v) for v in xyxy_raw)
                if len(xyxy_float) != 4:
                    continue
                detections.append(
                    Detection(
                        label=str(name),
                        confidence=float(box.conf[0]),
                        bbox_xyxy=(
                            xyxy_float[0],
                            xyxy_float[1],
                            xyxy_float[2],
                            xyxy_float[3],
                        ),
                    )
                )
            outputs.append(detections)
        return outputs


def read_split_manifest(manifest_path: Path) -> list[dict[str, Any]]:
    """Read a JSONL split manifest into records."""
    records: list[dict[str, Any]] = []
    with manifest_path.open(encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if line:
                records.append(json.loads(line))
    return records


def write_yolo_descriptor(
    split_summary: SplitSummary,
    output_dir: Path,
    *,
    dataset_root: Path,
    class_names: list[str],
) -> Path:
    """Write a trainable Ultralytics ``data.yaml`` from split manifests.

    ``dataset_root`` points at the raw dataset root; partition manifests under
    ``split_summary`` name the samples. Class names must match the training
    config's mapping order.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    descriptor = output_dir / "data.yaml"
    descriptor.write_text(
        (
            "# Generated by railway_detection from frozen split manifests.\n"
            f"split_id: {split_summary.split_id}\n"
            f"path: {dataset_root}\n"
            "train: train.jsonl\n"
            "val: val.jsonl\n"
            "test: test.jsonl\n"
            f"nc: {len(class_names)}\n"
            f"names: {class_names!r}\n"
        ),
        encoding="utf-8",
    )
    return descriptor


def copy_split_manifests(
    split_summary: SplitSummary, manifests_root: Path, output_dir: Path
) -> None:
    """Copy the frozen partition manifests next to the generated descriptor."""
    output_dir.mkdir(parents=True, exist_ok=True)
    for name in ("train", "val", "test"):
        source = manifests_root / f"{name}.jsonl"
        if source.exists():
            shutil.copy2(source, output_dir / f"{name}.jsonl")
